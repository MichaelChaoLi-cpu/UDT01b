#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_barrier_drainage_v1/neighbor_transfer_screen.csv
Output: data/processed/three_ward_analysis_contract_v1/instantaneous_transfer_screening_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_barrier_drainage_v1/neighbor_transfer_screen.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/instantaneous_transfer_screening_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'case': 'string', 'event_id': 'string', 'stage': 'string', 'measure': 'string'})

# --- Select and rename columns ---
rename_map = {
    "case": "Case",
    "event_id": "Rain Parent",
    "stage": "Receiving Water Scenario",
    "measure": "Measure Configuration",
    "frame": "Frame",
    "elapsed_s": "Elapsed Time",
    "outside_corridor_cell_area_head_increase_ge0_1m_km2": "Outside Corridor Depth Increase Area",
    "outside_corridor_cell_area_head_decrease_ge0_1m_km2": "Outside Corridor Depth Decrease Area",
    "native_cell_area_not_measured_flood_area": "Native Cell Screen Flag",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
