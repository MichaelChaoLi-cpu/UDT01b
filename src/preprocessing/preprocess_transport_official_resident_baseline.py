#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_population_block_stability_v1/official_2020_block_count_baseline.csv
Output: data/processed/three_ward_analysis_contract_v1/official_resident_baseline_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_population_block_stability_v1/official_2020_block_count_baseline.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/official_resident_baseline_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'block_id': 'string', 'ward': 'string', 'town_id': 'string', 'name': 'string', 'count_role': 'string', 'within_block_allocation_class': 'string'})

# --- Select and rename columns ---
rename_map = {
    "block_id": "Population Unit",
    "ward": "Ward",
    "town_id": "Town",
    "name": "Statistical Unit Name",
    "official_2020_residents": "Resident Population",
    "count_role": "Population Count Role",
    "within_block_allocation_class": "Population Allocation Class",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
