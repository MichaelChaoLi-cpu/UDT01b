#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_september_traffic_phases_v1/fixed_all_times_cohort_costs.csv
Output: data/processed/three_ward_final_evidence_v1/fixed_all_times_cohort_costs_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_september_traffic_phases_v1/fixed_all_times_cohort_costs.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/fixed_all_times_cohort_costs_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "frame": "Frame",
    "elapsed_hours": "Elapsed Hours",
    "stage": "Receiving Water Stage",
    "portfolio": "Measure Configuration",
    "all24states_common_request_proxy": "All24states Common Request Proxy",
    "common_cohort_mean_model_cost_min": "Common OD Cost",
    "same_time_noaction_cost_index": "Same Time Noaction Cost Index",
    "baseline_reachable_excluded_proxy": "Baseline Reachable Excluded Proxy",
    "cohort_empty": "Cohort Empty",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
