#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_population_totals_all_arms.csv
Output: data/processed/three_ward_final_evidence_v1/three_parent_population_totals_all_arms_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_population_totals_all_arms.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/three_parent_population_totals_all_arms_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "event": "Rainfall Parent",
    "portfolio": "Measure Configuration",
    "case": "Case",
    "stage": "Receiving Water Stage",
    "arm": "Arm",
    "bound": "Road Depth Branch",
    "buffer_m": "Population Access Candidate Radius",
    "scope": "Reporting Scope",
    "peak_loss_lower": "Peak Loss Lower",
    "peak_loss_upper": "Peak Loss Upper",
    "loss_lower_resident_hours": "Loss Lower Resident Hours",
    "loss_upper_resident_hours": "Loss Upper Resident Hours",
    "unresolved_stock": "Unresolved Stock",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
