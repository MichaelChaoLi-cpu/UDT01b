#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_road_comparison.csv
Output: data/processed/three_ward_final_evidence_v1/three_parent_road_comparison_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_road_comparison.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/three_parent_road_comparison_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "event": "Rainfall Parent",
    "case": "Case",
    "stage": "Receiving Water Stage",
    "branch": "Road Depth Branch",
    "scope": "Reporting Scope",
    "reference": "Reference Portfolio",
    "reference_closure_km_h": "Reference Closed Road Duration",
    "remaining_closure_km_h": "Remaining Closed Road Duration",
    "net_avoided_km_h": "Avoided Closed Road Duration",
    "restored_km_h": "Restored Road Exposure",
    "newly_closed_km_h": "Newly Closed Road Exposure",
    "peak_newly_closed_km": "Peak Newly Closed Road Length",
    "net_reduction_percent": "Net Reduction",
    "Q5_actual_extraction_m3": "Q5 Actual Extraction",
    "Q2p5_actual_extraction_m3": "Q2p5 Actual Extraction",
    "extra_extraction_m3": "Extra Extraction",
    "descriptive_incremental_km_h_per1000extra_m3": "Descriptive Incremental Kilometers Hours Per1000extra",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
