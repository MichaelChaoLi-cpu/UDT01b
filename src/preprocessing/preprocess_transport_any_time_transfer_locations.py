#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_barrier_drainage_v1/effect_summary/risk_transfer_ward_locations.csv
Output: data/processed/three_ward_analysis_contract_v1/any_time_transfer_locations_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_barrier_drainage_v1/effect_summary/risk_transfer_ward_locations.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/any_time_transfer_locations_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'event_id': 'string', 'stage': 'string', 'measure': 'string', 'scope': 'string'})

# --- Select and rename columns ---
rename_map = {
    "event_id": "Rain Parent",
    "stage": "Receiving Water Scenario",
    "measure": "Measure Configuration",
    "scope": "Reporting Scope",
    "ever_increased_cell_area_km2": "Any Time Depth Increase Area",
    "ever_decreased_cell_area_km2": "Any Time Depth Decrease Area",
    "center_assigned_10m_cell_area": "Cell Center Assignment Flag",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
