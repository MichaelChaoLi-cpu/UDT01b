#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_head_transfer_comparison.csv
Output: data/processed/three_ward_final_evidence_v1/three_parent_head_transfer_comparison_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_head_transfer_comparison.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/three_parent_head_transfer_comparison_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "event": "Rainfall Parent",
    "case": "Case",
    "stage": "Receiving Water Stage",
    "reference": "Reference Portfolio",
    "scope": "Reporting Scope",
    "peak_simultaneous_certain_head_rise_m2": "Peak Simultaneous Certain Head Rise",
    "any_time_certain_head_rise_union_m2": "Any Time Certain Head Rise Union",
    "peak_outside_actual_intakes_m2": "Peak Outside Actual Intakes",
    "any_time_newly_wet_subset_of_head_screen_m2": "Any Time Newly Wet Subset Of Head Screen",
    "threshold_m": "Threshold M",
    "dry_censor_bound_m": "Dry Censor Bound M",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
