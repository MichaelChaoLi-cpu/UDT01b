#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_Q5_vs_Q2p5_population_summary.csv
Output: data/processed/three_ward_final_evidence_v1/three_parent_Q5_vs_Q2p5_population_summary_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_cross_event_validation_v1/three_parent_Q5_vs_Q2p5_population_summary.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/three_parent_Q5_vs_Q2p5_population_summary_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "event": "Rainfall Parent",
    "stage": "Receiving Water Stage",
    "bound": "Road Depth Branch",
    "buffer_m": "Population Access Candidate Radius",
    "scope": "Reporting Scope",
    "net_lower_resident_hours": "Net Lower Resident Hours",
    "anchor_net_lower": "Anchor Net Lower",
    "net_upper_resident_hours": "Net Upper Resident Hours",
    "anchor_net_upper": "Anchor Net Upper",
    "restored_lower_resident_hours": "Restored Lower Resident Hours",
    "anchor_restored_lower": "Anchor Restored Lower",
    "restored_upper_resident_hours": "Restored Upper Resident Hours",
    "anchor_restored_upper": "Anchor Restored Upper",
    "new_loss_lower_resident_hours": "New Loss Lower Resident Hours",
    "anchor_new_loss_lower": "Anchor New Loss Lower",
    "new_loss_upper_resident_hours": "New Loss Upper Resident Hours",
    "anchor_new_loss_upper": "Anchor New Loss Upper",
    "maximum_new_loss_lower": "Maximum New Loss Lower",
    "maximum_new_loss_upper": "Maximum New Loss Upper",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
