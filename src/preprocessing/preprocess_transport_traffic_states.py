#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_barrier_drainage_v1/traffic/physical_traffic_outcomes.csv
Output: data/processed/three_ward_analysis_contract_v1/traffic_states_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_barrier_drainage_v1/traffic/physical_traffic_outcomes.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/traffic_states_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'event_id': 'string', 'stage': 'string', 'measure': 'string'})

# --- Select and rename columns ---
rename_map = {
    "event_id": "Rain Parent",
    "stage": "Receiving Water Scenario",
    "measure": "Measure Configuration",
    "frame": "Frame",
    "original_request_proxy": "Original Vehicle Demand",
    "served_proxy": "Served Vehicle Requests",
    "unreachable_proxy": "Unreachable Vehicle Requests",
    "completion_fraction_original": "Vehicle Completion Fraction",
    "common_survivor_original_request_proxy": "Common OD Vehicle Demand",
    "baseline_reachable_excluded_from_cost_proxy": "Excluded Baseline Reachable Requests",
    "common_survivor_cost_index": "Common OD Cost",
    "total_network_cost": "Total Network Cost",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
