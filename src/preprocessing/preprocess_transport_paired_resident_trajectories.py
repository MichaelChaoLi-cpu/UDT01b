#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_barrier_drainage_v1/paired_population_effects.csv
Output: data/processed/three_ward_analysis_contract_v1/paired_resident_trajectories_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_barrier_drainage_v1/paired_population_effects.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/paired_resident_trajectories_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'case': 'string', 'event_id': 'string', 'stage': 'string', 'measure': 'string', 'bound': 'string', 'scope': 'string'})

# --- Select and rename columns ---
rename_map = {
    "case": "Case",
    "event_id": "Rain Parent",
    "stage": "Receiving Water Scenario",
    "measure": "Measure Configuration",
    "frame": "Frame",
    "elapsed_s": "Elapsed Time",
    "bound": "Road Depth Bound",
    "buffer_m": "Population Candidate Radius",
    "scope": "Reporting Scope",
    "net_added_loss_lower": "Paired Additional Resident Loss Lower",
    "net_added_loss_upper": "Paired Additional Resident Loss Upper",
    "restored_lower": "Restored Resident Access Lower",
    "restored_upper": "Restored Resident Access Upper",
    "new_loss_lower": "New Resident Access Loss Lower",
    "new_loss_upper": "New Resident Access Loss Upper",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
