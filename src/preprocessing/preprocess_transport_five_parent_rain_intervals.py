#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_five_event_temporal_analysis_v1/rainfall_trajectories.csv
Output: data/processed/three_ward_analysis_contract_v1/five_parent_rain_intervals_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_five_event_temporal_analysis_v1/rainfall_trajectories.csv"
dst = ROOT / "data/processed/three_ward_analysis_contract_v1/five_parent_rain_intervals_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False, dtype={'event_id': 'string'})

# --- Select and rename columns ---
rename_map = {
    "event_id": "Rain Parent",
    "start_elapsed_s": "Interval Start",
    "end_elapsed_s": "Interval End",
    "source_area_mean_mm_h": "Mean Rainfall Rate",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
