from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_september_traffic_phases_v1/all_times_traffic_outcomes.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/all_times_traffic_outcomes_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "elapsed_hours": "Elapsed Hours",
    "case": "Case",
    "stage": "Receiving Water Stage",
    "portfolio": "Measure Configuration",
    "frame": "Frame",
    "original_core_request_proxy": "Original Core Vehicle Demand",
    "served_core_request_proxy": "Served Core Vehicle Demand",
    "unreachable_core_request_proxy": "Unreachable Vehicle Requests",
    "completion_fraction_original": "Completion Fraction Original",
    "common_cohort_original_request_proxy": "Common Cohort Original Request Proxy",
    "baseline_reachable_excluded_from_cost_proxy": "Baseline Reachable Excluded From Cost Proxy",
    "common_cohort_mean_cost_min": "Common OD Cost",
    "common_cohort_cost_index": "Common OD Cost Index",
    "common_cohort_over1min_worse_share": "Common Cohort Over1min Worse Share",
    "total_network_model_vehicle_seconds": "Total Network Model Vehicle Seconds",
    "total_network_cost_not_fixed_served_cohort": "Total Network Cost Not Fixed Served Cohort",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
