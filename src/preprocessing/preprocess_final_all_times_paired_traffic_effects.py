#!/usr/bin/env python3
"""Preprocessing script for data/processed/three_ward_s1r_september_traffic_phases_v1/all_times_paired_traffic_effects.csv
Output: data/processed/three_ward_final_evidence_v1/all_times_paired_traffic_effects_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/three_ward_s1r_september_traffic_phases_v1/all_times_paired_traffic_effects.csv"
dst = ROOT / "data/processed/three_ward_final_evidence_v1/all_times_paired_traffic_effects_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "elapsed_hours": "Elapsed Hours",
    "frame": "Frame",
    "stage": "Receiving Water Stage",
    "reference": "Reference Portfolio",
    "treatment": "Treatment",
    "restored_request_proxy": "Restored Vehicle Requests",
    "newly_unreachable_request_proxy": "Newly Unreachable Vehicle Requests",
    "net_avoided_unreachable_request_proxy": "Net Avoided Unreachable Request Proxy",
    "common_cohort_original_request_proxy": "Common Cohort Original Request Proxy",
    "common_cohort_cost_change_min": "Common OD Cost Change",
    "common_cohort_cost_change_percent": "Relative Common OD Cost Change",
    "same_cohort_over1min_worse_request_share": "Same Cohort Over1min Worse Request Share",
    "meaning": "Meaning",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
